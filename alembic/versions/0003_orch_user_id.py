"""add user_id to orchestration + linkedin_queue tables (P3-1)

Revision ID: 0003
Revises: 0002
Create Date: 2026-04-08

Why this exists
---------------
Phase 3 finishes multi-tenancy through the orchestration and LinkedIn
layers. Audit #7 landed `user_id` on every core table that was visible
through the HTTP API, but two internal tables were left untouched:

  - `orch_sequence_states`  -  one row per (lead, sequence). Scheduler
    work is picked up by lead_id, not user, so a cross-tenant filter
    was impossible without this column.
  - `linkedin_queue`  -  queue rows were grouped by action_type only, so
    a PhantomBuster launch could mix connect notes from different reps
    in the same batch (deep audit HIGH-8, partially fixed in P2-3 by
    resolving user_id on the fly; this column makes that resolution
    fast and persistent).

Migration also bridges the legacy env-var provider keys into the new
per-user provider registry (P3-2). The registry reads from
`app_settings` rows keyed as `__user__{admin_id}__{key}`. Until this
migration runs, a fresh install after P3-2 deploys would see empty
settings for the first admin and fall back to a no-op provider. We
seed those rows idempotently from the current process environment so
production keeps running without operator intervention.

Hand-written, NOT autogenerated  -  autogen would try to drop the
model/schema drift columns documented in 0001_baseline.py.

Production safety
-----------------
Additive only. Nullable columns with indexed lookups. The backfill
UPDATE statements only touch rows where `user_id IS NULL`, so re-
running the migration is a no-op. The app_settings seeding is also
guarded by a SELECT-before-INSERT check.
"""
from __future__ import annotations

import os

from alembic import op
import sqlalchemy as sa


# revision identifiers, used by Alembic.
revision = "0003"
down_revision = "0002"
branch_labels = None
depends_on = None


# Env vars that should be migrated into per-user app_settings rows so the
# new per-user provider registry (P3-2) can read them. Keys not set in the
# environment at migration time are silently skipped.
_LEGACY_ENV_KEYS = [
    "INSTANTLY_API_KEY",
    "INSTANTLY_CAMPAIGN_ID",
    "PHANTOMBUSTER_API_KEY",
    "PHANTOMBUSTER_CONNECT_AGENT_ID",
    "PHANTOMBUSTER_MESSAGE_AGENT_ID",
]


def upgrade() -> None:
    """Add user_id columns + backfill + legacy env-var migration."""
    # ── Schema changes ────────────────────────────────────────────────
    op.add_column(
        "orch_sequence_states",
        sa.Column("user_id", sa.String(), nullable=True),
    )
    op.create_index(
        "ix_orch_seq_states_user_id",
        "orch_sequence_states",
        ["user_id"],
    )

    op.add_column(
        "linkedin_queue",
        sa.Column("user_id", sa.String(), nullable=True),
    )
    op.create_index(
        "ix_linkedin_queue_user_id",
        "linkedin_queue",
        ["user_id"],
    )

    # ── Backfill orch_sequence_states.user_id from the owning prospect ─
    op.execute(
        """
        UPDATE orch_sequence_states
        SET user_id = (
            SELECT p.user_id FROM prospects p
            WHERE p.id = orch_sequence_states.lead_id
        )
        WHERE user_id IS NULL
        """
    )

    # ── Backfill linkedin_queue.user_id from campaign, fallback to prospect ─
    op.execute(
        """
        UPDATE linkedin_queue
        SET user_id = COALESCE(
            (SELECT c.user_id FROM campaigns c WHERE c.id = linkedin_queue.campaign_id),
            (SELECT p.user_id FROM prospects p WHERE p.id = linkedin_queue.prospect_id)
        )
        WHERE user_id IS NULL
        """
    )

    # ── Migrate legacy env-var provider keys into per-user app_settings ─
    #
    # The per-user provider registry (P3-2) reads from rows with the key
    # convention `__user__{admin_id}__{original_key}`. We seed those
    # rows from the current os.environ so the running prod campaign
    # keeps its provider credentials available on the first request
    # after this migration runs.
    conn = op.get_bind()
    admin_row = conn.execute(
        sa.text(
            "SELECT id FROM users WHERE role = 'admin' "
            "ORDER BY created_at ASC LIMIT 1"
        )
    ).fetchone()

    if admin_row is None:
        # First-run install  -  no admin user yet. The dashboard auto-seeds
        # one on first boot; at that point the operator can re-run this
        # migration or set the values via the settings API. Nothing to do.
        return

    admin_id = admin_row[0]

    for env_key in _LEGACY_ENV_KEYS:
        value = os.environ.get(env_key, "").strip()
        if not value:
            continue

        setting_key = f"__user__{admin_id}__{env_key}"

        # Idempotent: skip if the row already exists (either from a
        # previous migration run or because the operator set it manually).
        existing = conn.execute(
            sa.text("SELECT 1 FROM app_settings WHERE key = :k"),
            {"k": setting_key},
        ).fetchone()
        if existing:
            continue

        conn.execute(
            sa.text(
                "INSERT INTO app_settings (key, value, user_id) "
                "VALUES (:k, :v, :uid)"
            ),
            {"k": setting_key, "v": value, "uid": admin_id},
        )


def downgrade() -> None:
    """Drop the new columns and indexes.

    Intentionally does NOT reverse the app_settings inserts  -  leaving
    them in place is harmless (the per-user provider registry simply
    ignores unknown keys) and avoids accidentally destroying
    operator-supplied provider credentials during a rollback.
    """
    op.drop_index("ix_linkedin_queue_user_id", table_name="linkedin_queue")
    op.drop_column("linkedin_queue", "user_id")

    op.drop_index("ix_orch_seq_states_user_id", table_name="orch_sequence_states")
    op.drop_column("orch_sequence_states", "user_id")
